def _gen_slurm(spec: wavespec.WaveSpec, runs: list[wavespec.Run], hdr: str) -> str:
  """Cap-aware, re-runnable sbatch submission for target: slurm stages.

  Three things this encodes that a hand-written loop keeps having to remember:

  1. Many clusters cap submitted+running jobs per user (Q_SLURM_MAX_JOBS,
     12 by default). Blowing past it rejects submissions, so the script
     submits up to the cap and tells you how many are left -- rerun until it
     says none.
  2. `--export=ALL` inherits the submitting shell. Submitting from a shell with
     modules loaded leaks their environment into the job and has produced
     segfaults; this refuses to submit from a dirty shell rather than letting
     you find out an hour later.
  3. Runs already complete (by the spec's own predicates) or already queued
     under the same job name are skipped, so rerunning is safe.
  """
  lines = [hdr.rstrip("\n"),
           ("""# Submit this wave's slurm stages. Re-runnable: run until it reports 0 left.
#   usage: submit_slurm.sh [--dry-run]
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
{root_preamble}source "$FLEET_HOME/fleet/common.sh"

DRY=0; [ "${1:-}" = "--dry-run" ] && DRY=1
MAX_JOBS="${Q_SLURM_MAX_JOBS:-12}"
SLURM_ACCOUNT="${Q_SLURM_ACCOUNT:-}"
SLURM_PARTITION="${Q_SLURM_PARTITION:-}"
SLURM_GRES="${Q_SLURM_GRES:-gpu:1}"
: "${REPO:=${FLEET_PROJECT_REPO:-}}"
[ -n "$REPO" ] || { echo "ERROR: set REPO or FLEET_PROJECT_REPO (where the sbatch scripts live)" >&2; exit 2; }

# (2) module leakage: --export=ALL carries this shell into every job.
#
# The incident behind this: a day of rc=139 segfaults ~30s in, at the first
# GPU touch, caused by `module load cuda` + `module load python` + `conda
# activate` in the submitting shell -- their PATH/LD_LIBRARY_PATH shadowed the
# job environment's pinned CUDA wheels.
#
# It was NOT caused by the modules the cluster loads for every login shell
# (e.g. slurm, which PROVIDES sbatch). Refusing on those made the first version
# of this guard unpassable. So: refuse on anything OUTSIDE a configurable
# baseline, and name it.
MOD_BASELINE="${FL_MODULE_BASELINE:-slurm}"
if [ -z "${FL_SKIP_MODULE_GUARD:-}" ] && [ -n "${LOADEDMODULES:-}" ]; then
  unexpected=""
  IFS=':' read -ra _mods <<< "$LOADEDMODULES"
  for m in "${_mods[@]}"; do
    [ -n "$m" ] || continue
    base="${m%%/*}"
    case " $MOD_BASELINE " in *" $base "*) ;; *) unexpected="$unexpected $m" ;; esac
  done
  if [ -n "$unexpected" ]; then
    echo "REFUSING TO SUBMIT: non-baseline modules loaded:$unexpected" >&2
    echo "  LOADEDMODULES=$LOADEDMODULES" >&2
    echo "  --export=ALL leaks these into every job; a cuda/python module here" >&2
    echo "  once shadowed the job's pinned CUDA libraries and segfaulted every" >&2
    echo "  GPU job." >&2
    echo "  Fix: 'module purge && module load slurm' in a fresh shell, or list your" >&2
    echo "  login-shell modules in FL_MODULE_BASELINE." >&2
    echo "  Override (only if you are sure): FL_SKIP_MODULE_GUARD=1" >&2
    exit 2
  fi
fi

command -v squeue >/dev/null 2>&1 || {
  echo "ERROR: squeue not found -- run this on a Slurm login node." >&2; exit 2; }
cur="$(squeue -h -u "$USER" | wc -l)" || {
  echo "ERROR: squeue failed; refusing to guess the queue depth and risk" >&2
  echo "       submitting past the cap." >&2; exit 2; }
slots=$(( MAX_JOBS - cur ))
echo "slurm: $cur job(s) in queue, cap $MAX_JOBS, $slots slot(s) free"
[ "$slots" -gt 0 ] || { echo "at cap; rerun later"; exit 0; }

queued="$(squeue -h -u "$USER" -o '%j' 2>/dev/null || true)"
submitted=0; skipped=0; left=0
""").replace("{root_preamble}", _preamble())]

  for r in runs:
    sb = r.sbatch
    # Export values are DOUBLE-quoted so the submitting shell expands $RUNROOT,
    # $REPO and friends before sbatch sees them. shlex.quote would single-quote
    # them, and `--export` values are not shell-expanded by sbatch -- nor does
    # bash ever re-expand a variable's VALUE -- so the job would receive the
    # literal string "${RUNROOT}/run_..." and fail its own directory check
    # with a path that looks correct in every log (it did, on the first slurm
    # wave). Specs write ${RUNROOT} exactly as they do for box lanes; the
    # difference is only WHICH shell expands it.
    def _export_val(v: str) -> str:
      v = str(v)
      # Command substitution in an export value would run at submit time with
      # the submitter's environment -- never intended, and hard to spot.
      for bad in ("`", "$("):
        if bad in v:
          raise SpecError(f"sbatch export value may not contain {bad!r}: {v!r}")
      return '"' + v.replace('"', r'\"') + '"'

    exports = ",".join(f"{k}={_export_val(v)}"
                       for k, v in (sb.get("export") or {}).items())
    opts = [
        f'${{SLURM_ACCOUNT:+--account="$SLURM_ACCOUNT"}}',
        f'${{SLURM_PARTITION:+--partition="$SLURM_PARTITION"}}',
        f'--gres={shlex.quote(str(sb.get("gres", "$SLURM_GRES")))}'.replace(
            "'$SLURM_GRES'", '"$SLURM_GRES"'),
        f'--time={shlex.quote(str(sb.get("time", "12:00:00")))}',
        f'--job-name={shlex.quote(r.run_id)}',
    ]
    # PIN THE GPU MODEL. A heterogeneous `gpu` partition (some nodes one GPU
    # model, some another) lets Slurm scatter one panel across both. That is
    # not a performance detail: a bfloat16 evaluation re-run on the SAME GPU
    # was byte-identical, yet moved its headline metric by up to 0.11 across
    # GPU models, and one panel had already been split down the middle that
    # way before anyone noticed. A panel must land on ONE model: set
    # `sbatch: {constraint: <feature>}` per stage (or Q_SLURM_CONSTRAINT as the
    # default); "" opts out deliberately.
    constraint = str(sb.get("constraint", os.environ.get("Q_SLURM_CONSTRAINT", "")))
    if constraint:
      opts.append(f'--constraint={shlex.quote(constraint)}')
    for extra in (sb.get("options") or []):
      opts.append(str(extra))
    base = "ALL,REPO=\"$REPO\",RUNROOT=\"$RUNROOT\""
    lines.append(f"""
# --- {r.run_id} ---
if printf '%s\\n' "$queued" | grep -qxF {shlex.quote(r.run_id)}; then
  echo "  SKIP already queued: {r.run_id}"; skipped=$((skipped+1))
elif [ "$slots" -le 0 ]; then
  left=$((left+1))
else
  if [ "$DRY" = 1 ]; then
    echo "  WOULD SUBMIT {r.run_id}"
  else
    sbatch {' '.join(opts)} \\
      --export={base}{("," + exports) if exports else ""} \\
      "$REPO/{sb['script']}"
  fi
  submitted=$((submitted+1)); slots=$((slots-1))
fi""")

  lines.append("""
echo
echo "submitted=$submitted skipped=$skipped left=$left"
[ "$left" -eq 0 ] && echo "all submitted" \\
  || echo "$left run(s) did not fit under the cap -- rerun this script when jobs drain"
""")
  return "\n".join(lines) + "\n"


def _producer_vars(cmd: str) -> tuple[str, set[str]]:
  """(repo-relative producer, variables the command sets) for one lane command.

  Only shell producers are returned: a `python -m pkg.mod` invocation has no
  file to grep for `$VAR`, and guessing one would turn a real gate into a
  guess."""
  m = re.search(r"\bbash\s+(scripts/[\w./-]+)", cmd)
  if not m:
    return "", set()
  names = set(re.findall(r"(?:^|[;&\s(])([A-Z][A-Z0-9_]{2,})=", cmd))
  # Set by the queue wrapper, not by the wave; the producer need not read them.
  names -= {"FL_TASK_NAME", "FL_ABORT_ON_FAIL", "PYTHONPATH", "REPO", "RUNROOT"}
  return m.group(1), names


def gen(spec: wavespec.WaveSpec, out: Path, lanes: list[str]) -> dict:
  out.mkdir(parents=True, exist_ok=True)
  hdr = HEADER.format(spec=spec.path)
  all_runs = spec.runs()
  summary: dict = {"wave_id": spec.wave_id, "stages": {}, "lane_files": []}
  producer_vars: dict[str, set[str]] = {}
  try:
    proj = _project_repo()
    repo_sha = "" if proj is None else subprocess.run(
        ["git", "-C", str(proj), "rev-parse", "--short", "HEAD"],
        capture_output=True, text=True, timeout=20).stdout.strip()
  except Exception as e:
    print(f"WARN: could not read repo HEAD for the generation stamp: {e}",
          file=sys.stderr)
    repo_sha = ""
  repo_sha = repo_sha or "unknown"

  # -- RUN_IDS.txt : the approval gate --------------------------------------
  lines = [f"wave_id: {spec.wave_id}", f"spec:    {spec.path}"]
  lines.append("")
  for st in spec.stages:
    runs = st.expanded()
    summary["stages"][st.name] = {
        "count": len(runs), "target": st.target, "kind": st.kind,
        "on_failure": st.on_failure,
        "per_gpu": spec.kinds[st.kind].per_gpu if st.kind in spec.kinds else 1,
    }
    lines.append(f"=== stage {st.name}  [{st.target}]  kind={st.kind}  "
                 f"on_failure={st.on_failure}  n={len(runs)} ===")
    lines.extend(f"  {r.run_id}" for r in runs)
    lines.append("")
  lines.append(f"TOTAL RUNS: {len(all_runs)}")
  lines.append("")
  lines.append("Check this list before submitting. run_ids are consumed by the")
  lines.append("checker, the pull and the bundle; a wrong expansion here")
  lines.append("propagates into every downstream artifact.")
  _w(out / "RUN_IDS.txt", "\n".join(lines) + "\n")

  # -- runs.json : the canonical table ---------------------------------------
  _w(out / "runs.json", json.dumps({
      "wave_id": spec.wave_id,
      "spec": str(spec.path),
      "bundle": (None if not spec.bundle else {
          "prefix": spec.bundle.prefix,
          "include_stages": spec.bundle.include_stages,
          "cloud_logs": spec.bundle.cloud_logs}),
      "stages": [{"name": s.name, "target": s.target, "kind": s.kind,
                  "on_failure": s.on_failure, "needs": s.needs} for s in spec.stages],
      "runs": [{"stage": r.stage, "kind": r.kind, "target": r.target,
                "run_id": r.run_id, "cmd": r.cmd, "vars": r.vars,
                "logdir": r.logdir, "outputs": r.outputs, "inputs": r.inputs,
                "done_when": [{p.kind: p.arg} for p in r.done_when]}
               for r in all_runs],
  }, indent=1) + "\n")

  # -- lane command files ----------------------------------------------------
  submit_lines = [hdr, "# Ship the wave dir to a box, then queue each lane.",
                  "#   usage: submit.sh <box>", "set -euo pipefail",
                  'N="${1:?usage: submit.sh <box>}"',
                  'HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"',
                  _preamble() + COMMON.rstrip("\n"),
                  'fl_require_instance "$N"',
                  # The box's RUNROOT is NOT this machine's. Ask the box.
                  #
                  # Both alternatives were live bugs, found on the first real
                  # use of submit.sh: expanding "$RUNROOT" here sent the wave
                  # dir to a controller path that does not exist on the box,
                  # while leaving "$REMOTE" for the box to expand hit an unset
                  # variable (it is defined only in THIS script), so the queue
                  # lines died on `set -u` after the rsync had already claimed
                  # success.
                  'REMOTE_ROOT="$(fl_ssh_box "$N" \'printf %s "$RUNROOT"\')"',
                  '[ -n "$REMOTE_ROOT" ] || { echo "ERROR: cannot read RUNROOT'
                  ' on box $N" >&2; exit 1; }',
                  f'REMOTE="$REMOTE_ROOT/_waves/{spec.wave_id}"', "",
                  "# rsync rather than heredoc: no quoting survives ssh reliably,",
                  "# and it leaves the exact submitted commands on the box.",
                  'fl_ssh_box "$N" "mkdir -p \\"$REMOTE\\""',
                  '# --checksum: these are small text files that can be',
                  '# regenerated at the same size, and size+mtime would skip them.',
                  'rsync -az --checksum --info=progress2 \\',
                  '  -e "ssh -p $(fl_port "$N") ${FL_SSH_OPTS[*]}" \\',
                  f'  "$HERE/" "root@$(fl_ip "$N"):$REMOTE/"', ""]

  for st in spec.stages:
    if st.target != "lanes":
      continue
    per_gpu = spec.kinds[st.kind].per_gpu if st.kind in spec.kinds else 1
    runs = wavespec.balanced_order(st.expanded())
    units = wavespec.pair_runs(runs, per_gpu)
    by_lane = wavespec.assign_lanes(units, lanes)
    for ln, lane_units in by_lane.items():
      if not lane_units:
        continue
      fname = f"lane_{st.name}_{ln}.cmds"
      body = [f"# {spec.wave_id} / stage {st.name} / lane {ln} / "
              f"{len(lane_units)} queued task(s), {sum(len(u) for u in lane_units)} run(s)"]
      for u in lane_units:
        for r in u:
          sc, nm = _producer_vars(r.cmd)
          if sc:
            producer_vars.setdefault(sc, set()).update(nm)
      for i, u in enumerate(lane_units):
        body.append(cmd_line(u, f"{spec.wave_id}_{st.name}_l{ln}_pair{i:02d}"))
      _w(out / fname, "\n".join(body) + "\n")
      summary["lane_files"].append(fname)
      abort = "1" if st.on_failure == "abort" else "0"
      submit_lines.append(
          f'echo "-- stage {st.name} lane {ln}: {len(lane_units)} task(s) --"')
      submit_lines.append(
          # Double quotes: $REMOTE must expand HERE, to the path we just
          # resolved on the box, not remotely where it does not exist.
          f'fl_ssh_box "$N" "FL_ABORT_ON_FAIL={abort} '
          f'fl_queue_or_add \\"$REMOTE/{fname}\\" {ln}"')
  submit_lines += ["", 'echo "submitted. verify with: fleet status $N"']
  _w(out / "submit.sh", "\n".join(submit_lines) + "\n", executable=True)

  # -- Slurm submission ------------------------------------------------------
  slurm_runs = [r for r in all_runs if r.target == "slurm"]
  if slurm_runs:
    _w(out / "submit_slurm.sh", _gen_slurm(spec, slurm_runs, hdr), executable=True)
    summary["slurm_runs"] = len(slurm_runs)

  # -- preflight (remote half) ----------------------------------------------
  wave_inputs = sorted({i for r in all_runs for i in r.inputs})
  pf = [hdr, "# Run ON a box. Every check here corresponds to a failure",
        "# that has actually cost work before.", "set -uo pipefail",
        "source /root/.fleet_env", "fail=0",
        'ok () { printf "  PASS %s\\n" "$1"; }',
        'bad () { printf "  FAIL %s\\n" "$1"; fail=1; }', "",
        'echo "== repo present (an empty $REPO fails as scattered ENOENT, never one message) =="',
        '[ -n "$(ls -A "$REPO" 2>/dev/null)" ] && ok "REPO=$REPO" || bad "EMPTY or missing REPO=$REPO -- run push-repo"', "",
        'echo "== interpreter =="',
        '"${FL_PYTHON:-python3}" -c "import sys" 2>/dev/null \\',
        '  && ok "python ${FL_PYTHON:-python3}" || bad "python broken: ${FL_PYTHON:-python3}"', "",
        # On one box /usr/bin/rsync was a 0-byte non-executable stub (the disk
        # filled mid-write). ssh still worked, so it presented as "rsync:
        # connection unexpectedly closed" on the controller -- a sender-side
        # error message for a receiver-side broken binary.
        'echo "== transfer tooling =="',
        'for b in rsync tar; do',
        '  p="$(command -v "$b" 2>/dev/null)"',
        '  if [ -z "$p" ]; then bad "MISSING $b"',
        '  elif [ ! -x "$p" ]; then bad "$b not executable ($p)"',
        '  elif [ ! -s "$p" ]; then bad "$b is a 0-byte stub ($p) -- reinstall it"',
        '  else ok "$b $(du -h "$p" | cut -f1)"; fi',
        "done", "",
        'echo "== disk =="',
        'pct="$(df -P "$RUNROOT" | awk \'NR==2{gsub(/%/,"",$5); print $5}\')"',
        '[ "${pct:-100}" -lt 90 ] && ok "disk ${pct}% used" || bad "disk ${pct}% used"', ""]
  if wave_inputs:
    pf += ['echo "== inputs =="']
    for d in wave_inputs:
      pf.append(f'[ -e "$RUNROOT/{d}" ] && ok {shlex.quote(d)} || bad "MISSING input {d}"')
    pf.append("")
  # ---- stale-producer gate ------------------------------------------------
  # A lane command never pulls: it does `cd "$REPO"` and runs whatever is
  # there. When a box's copy predates the commit that added an override, the
  # variable is simply UNREAD -- one `FOO_FLAG=False` prefix bound nothing and
  # four runs trained as the wrong arm for 6.3 h each, while RUN_ID/TASK/SEED
  # from the same prefix bound fine because those existed in the old script.
  # Existence checks cannot see this; only reading the producer can.
  #
  # So: for every producer a lane invokes, assert on the BOX'S OWN COPY
  # that each variable the command sets is actually referenced. This is the
  # check that would have caught the incident at preflight instead of at read.
  if producer_vars:
    pf += ['echo "== producer reads every variable the wave sets =="']
    for script, names in sorted(producer_vars.items()):
      pf.append(f'if [ ! -e "$REPO/{script}" ]; then bad "MISSING producer {script}"; else')
      for v in sorted(names):
        pat = shlex.quote("[$]\\{?" + v + "\\b")
        # The variable NAME is data here, not something to expand: an
        # unescaped $VAR inside these double-quoted messages is expanded by the
        # remote shell and, under `set -u`, kills the preflight outright.
        pf.append(
            f'  grep -qE {pat} "$REPO/{script}" '
            f'&& ok "{script} reads \\${v}" '
            f'|| bad "STALE PRODUCER: {script} never reads \\${v} -- the wave '
            f'sets it and it would bind NOTHING (run push-repo)"')
      pf.append("fi")
    pf.append("")

  # Generation-time HEAD of FLEET_PROJECT_REPO, asserted against the box's
  # push-repo stamp. The
  # variable check above is the load-bearing one; this reports the drift that
  # explains it.
  pf += ['echo "== repo generation stamp =="',
         f'want={shlex.quote(repo_sha)}',
         'got="$(cat "${FLEET_BOX_HOME:-/root/fleet}/VERSION" 2>/dev/null | head -1)"',
         'case "$got" in',
         '  "$want"*|*"${want%%-*}"*) ok "box repo matches wave generation ($want)" ;;',
         '  "") bad "no VERSION stamp on the box -- run push-repo" ;;',
         '  *) bad "REPO DRIFT: wave generated at $want, box has $got -- run push-repo" ;;',
         'esac', "",
         ]
  pf += ['echo "== helpers =="',
         '. "${FLEET_BOX_HOME:-/root/fleet}/lanes.sh" 2>/dev/null',
         'type fl_queue_or_add >/dev/null 2>&1 && ok "helpers loaded ($(fl_version))" \\',
         '  || bad "helpers not loaded -- run push-repo"', "",
         '[ "$fail" -eq 0 ] && echo "PREFLIGHT PASS" || echo "PREFLIGHT FAIL"',
         'exit "$fail"']
  _w(out / "preflight_remote.sh", "\n".join(pf) + "\n", executable=True)

  # -- input push ------------------------------------------------------------
  if wave_inputs:
    inc = " \\\n  ".join(include_args(wave_inputs))
    _w(out / "push_inputs.sh", f"""{hdr}# Push this wave's declared inputs to a box.
#   usage: push_inputs.sh <box>
set -euo pipefail
N="${{1:?usage: push_inputs.sh <box>}}"
HERE="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
{_preamble()}{COMMON}fl_require_instance "$N"

# Fail before transferring rather than half way through: a missing input is a
# spec error, and discovering it after 40 minutes of rsync is expensive.
missing=0
for d in {' '.join(shlex.quote(d) for d in wave_inputs)}; do
  [ -e "$RUNROOT/$d" ] || {{ echo "MISSING input: $RUNROOT/$d" >&2; missing=1; }}
done
[ "$missing" -eq 0 ] || {{ echo "ERROR: wave_inputs missing locally; nothing pushed" >&2; exit 1; }}

fl_ssh_box "$N" 'mkdir -p "$RUNROOT"'
rsync "${{FL_RSYNC_OPTS[@]}}" \\
  -e "ssh -p $(fl_port "$N") ${{FL_SSH_OPTS[*]}}" \\
  {inc} \\
  --exclude='*' \\
  "$RUNROOT/" "root@$(fl_ip "$N"):$FLEET_REMOTE_RUNROOT/"
""", executable=True)

  # -- result pull -----------------------------------------------------------
  lane_outputs = sorted({o for r in all_runs if r.target == "lanes" for o in r.outputs})
  if lane_outputs:
    inc = " \\\n  ".join(include_args(lane_outputs))
    logs = " \\\n  ".join(
        f"--include={shlex.quote('/_cloud_logs/' + r + '.out')}" for r in lane_outputs)
    _w(out / "pull_results.sh", f"""{hdr}# Pull this wave's results from boxes into the local RUNROOT.
#   usage: pull_results.sh <box> [box...]
set -euo pipefail
HERE="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
{_preamble()}{COMMON}[ $# -gt 0 ] || {{ echo "usage: pull_results.sh <box>..." >&2; exit 2; }}

# rsync exit 24 is "some files vanished before they could be transferred". When
# the source box is still COMPUTING -- which is the normal case, and the
# case worth pulling for -- checkpoints rotate mid-transfer and 24 is routine.
# It is a warning, not a failure. Under `set -e` it aborted the whole script
# after the first live box, so every LATER box was silently skipped and the
# run still looked like it had merely "finished" (a pull of four boxes stopped
# after the second, and only the log's missing "pulled" line showed it).
# 23 (partial transfer / real error) is NOT tolerated.
rs () {{
  rsync "$@"; local rc=$?
  [ "$rc" -eq 0 ] || [ "$rc" -eq 24 ] || return "$rc"
  [ "$rc" -eq 24 ] && echo "  (rsync 24: files rotated mid-copy on a live box -- expected)"
  return 0
}}

failed=""
for N in "$@"; do
  fl_require_instance "$N"
  echo "-- pull from box $N --"

  # Pass 1: payload. Large, resumable, size/mtime based.
  rs "${{FL_RSYNC_OPTS[@]}}" \\
    -e "ssh -p $(fl_port "$N") ${{FL_SSH_OPTS[*]}}" \\
    {inc} \\
    --include='/_cloud_logs/' \\
    {logs} \\
    --include='/_cloud_logs/worker_shard*.out' \\
    --include='/_cloud_logs/events.jsonl' \\
    --exclude='*' \\
    "root@$(fl_ip "$N"):$FLEET_REMOTE_RUNROOT/" "$RUNROOT/"

  # Pass 2: mutable witnesses only, checksum-forced. An earlier mid-run pull
  # can leave a stale progress/marker file that size+mtime will not correct,
  # and a stale witness is read as truth by the checker. Deliberately NOT
  # --append-verify, and deliberately scoped to tiny files.
  # `latest` is in this list because it is the ONE payload file that is both
  # MUTABLE and CONSTANT-LENGTH: --append-verify skips same-size files, so it
  # froze at whatever checkpoint the first pull saw. That once left ten runs
  # naming a ~105k-step checkpoint while the ~495k ones sat beside them, and a
  # downstream probe reported OK on the wrong model.
  # Add your own small mutable files with FL_PULL_WITNESSES (space-separated).
  wit=()
  for w in ${{FL_PULL_WITNESSES:-}}; do wit+=(--include="$w"); done
  rs -az -c --ignore-times --info=progress2 \\
    -e "ssh -p $(fl_port "$N") ${{FL_SSH_OPTS[*]}}" \\
    --include='*/' \\
    --include='*_DONE' --include='done' --include='_rc.txt' \\
    --include='latest' --include='*.STEP' "${{wit[@]}}" \\
    --exclude='*' \\
    {inc} \\
    "root@$(fl_ip "$N"):$FLEET_REMOTE_RUNROOT/" "$RUNROOT/" || failed="$failed $N"
done
if [ -n "$failed" ]; then
  echo "PULL INCOMPLETE for box(es):$failed" >&2
  echo "  the others were pulled; re-run for just these once reachable" >&2
  exit 1
fi
echo "pulled. verify with: fleet check {spec.wave_id}"
""", executable=True)

  # -- bundle ----------------------------------------------------------------
  if spec.bundle:
    br = sorted({o for r in all_runs if r.stage in spec.bundle.include_stages
                 for o in r.outputs})
    globs = spec.bundle.cloud_logs or []
    _w(out / "bundle.sh", f"""{hdr}# Bundle this wave for transfer to the analysis machine.
set -euo pipefail
HERE="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
{_preamble()}{COMMON}
bundle="$RUNROOT/bundles/{spec.bundle.prefix}_$(date +%Y%m%d_%H%M%S)"
mkdir -p "$bundle/runroot" "$bundle/_cloud_logs"

# COMPLETION.txt is written by the same checker that gates the read, so the
# bundle cannot claim a completeness its own predicates would reject.
python3 "$FLEET_HOME/fleet/wavecheck.py" \\
  "$FLEET_WAVES/{spec.wave_id}" --runroot "$RUNROOT" \\
  > "$bundle/COMPLETION.txt" || true
cat "$bundle/COMPLETION.txt"

# Outputs may be directories (one per run) or loose files in a shared folder
# (e.g. probe results), so preserve the relative path rather than flattening into runroot/.
for run in {' '.join(shlex.quote(r) for r in br)}; do
  if [ -e "$RUNROOT/$run" ]; then
    mkdir -p "$bundle/runroot/$(dirname "$run")"
    cp -al "$RUNROOT/$run" "$bundle/runroot/$run" 2>/dev/null \
      || cp -a "$RUNROOT/$run" "$bundle/runroot/$run"
  else
    echo "WARN: missing output $run" >&2
  fi
done

shopt -s nullglob
for pat in {' '.join(shlex.quote(g) for g in globs) or "''"}; do
  [ -n "$pat" ] || continue
  for f in "$RUNROOT"/_cloud_logs/$pat; do cp -a "$f" "$bundle/_cloud_logs/"; done
done

cp -a "$HERE/runs.json" "$HERE/RUN_IDS.txt" "$bundle/" 2>/dev/null || true

# LINK-VS-COPY MODE. The loop above prefers `cp -al`, which HARD LINKS into
# the live runroot instead of duplicating bytes. A hard-linked bundle is a
# VIEW, not an archive: if anything later writes to those run dirs the bundle
# mutates with them. This is not hypothetical -- an in-place RESUME appended
# into a bundle that was supposed to be immutable, and its
# manifest then failed on 1282 files. Record the mode
# inside the bundle so a reader knows what it is holding.
mode_f="$bundle/_BUNDLE_MODE.txt"
shared=0; total=0
for f in $(find "$bundle/runroot" -type f 2>/dev/null | head -500); do
  total=$((total+1))
  [ "$(stat -c %h "$f")" -gt 1 ] && shared=$((shared+1))
done
echo "runroot storage mode: $shared of $total sampled files are HARD LINKS (nlink>1)" > "$mode_f"
if [ "$shared" -gt 0 ]; then
  echo "=> This bundle SHARES STORAGE with \\$RUNROOT. It is a VIEW, not an archive." >> "$mode_f"
  echo "   An in-place RESUME/EXTENSION appends to scores.jsonl / metrics.jsonl /" >> "$mode_f"
  echo "   other append-only logs and will mutate this bundle too, breaking its manifest." >> "$mode_f"
  echo "   ARCHIVE OF RECORD = the local rsync copy + its committed manifest." >> "$mode_f"
  echo "   Before any planned in-place resume of these runs, either" >> "$mode_f"
  echo "   materialize this bundle (real copy) or mark it superseded." >> "$mode_f"
else
  echo "=> All sampled files are unshared real copies." >> "$mode_f"
fi
cat "$mode_f"

# sha256 manifest of everything in the bundle, written last.
( cd "$bundle" && find . -type f ! -name MANIFEST.sha256 -print0 | sort -z \\
    | xargs -0 sha256sum > MANIFEST.sha256 )
echo "manifest: $(wc -l < "$bundle/MANIFEST.sha256") files"
echo "$bundle"
""", executable=True)

  return summary


def main() -> int:
  ap = argparse.ArgumentParser(description=__doc__,
                               formatter_class=argparse.RawDescriptionHelpFormatter)
  ap.add_argument("wave", help="waves/<id> directory or a spec.json/yaml path")
  ap.add_argument("--lanes", default="0,1,2,3",
                  help="lane ids (one per GPU) for target: lanes stages (default 0,1,2,3)")
  ap.add_argument("--out", default=None, help="output dir (default <wave>/generated)")
  ap.add_argument("--quiet", action="store_true")
  ap.add_argument("--only-runs", default=None, metavar="FILE",
                  help="regenerate lane files for just these run_ids (one per "
                       "line, e.g. `wavecheck.py --pending`). Used by requeue: "
                       "the retry set is derived from the checker, never retyped.")
  args = ap.parse_args()

  try:
    spec = wavespec.load(args.wave)
  except SpecError as e:
    print(f"SPEC ERROR: {e}", file=sys.stderr)
    return 2

  lanes = [x.strip() for x in args.lanes.split(",") if x.strip()]
  default_out = (Path(args.wave) if Path(args.wave).is_dir()
                 else spec.path.parent) / "generated"

  if args.only_runs:
    keep = {ln.strip() for ln in Path(args.only_runs).read_text().split() if ln.strip()}
    known = {r.run_id for r in spec.runs()}
    unknown = keep - known
    if unknown:
      print(f"ERROR: {len(unknown)} run_id(s) not in this wave: "
            f"{sorted(unknown)[:5]}", file=sys.stderr)
      return 2
    # Freeze the surviving runs as explicit entries. run_id and cmd are carried
    # verbatim from the original expansion, so a requeued task is byte-identical
    # to what first ran -- a retry must not be a re-derivation.
    for st in spec.stages:
      kept = [{**r.vars, "run_id": r.run_id, "cmd": r.cmd}
              for r in st.expanded() if r.run_id in keep]
      st.explicit_runs = kept
      st.expand = {}
    if not any(st.explicit_runs for st in spec.stages):
      print("nothing to requeue: every run in the filter is already complete")
      return 0

  out = Path(args.out) if args.out else default_out

  try:
    summary = gen(spec, out, lanes)
  except SpecError as e:
    print(f"SPEC ERROR: {e}", file=sys.stderr)
    return 2

  if not args.quiet:
    print((out / "RUN_IDS.txt").read_text())
    print(f"generated -> {out}")
    for st, info in summary["stages"].items():
      print(f"  stage {st:<12} {info['count']:>4} run(s)  target={info['target']:<10}"
            f" per_gpu={info['per_gpu']}  on_failure={info['on_failure']}")
    print(f"  lane files: {len(summary['lane_files'])}")
    print()
    print("APPROVAL GATE: nothing is submitted by this command. Read RUN_IDS.txt,")
    print("check it, then run generated/submit.sh <box>.")
  return 0


if __name__ == "__main__":
  sys.exit(main())
