#!/usr/bin/env python3
"""Generate every per-wave artifact from one spec.

Emits into $FLEET_WAVES/<wave_id>/generated/:

  RUN_IDS.txt          the approval gate -- expanded ids and counts
  runs.json            canonical run table (consumed by check/pull/bundle)
  lane_<stage>_<n>.cmds  queue command files, pairs already grouped
  submit.sh            rsync the wave dir to a box, then queue each lane
  submit_slurm.sh      cap-aware sbatch submission for target: slurm stages
  preflight_remote.sh  assertions to run ON a box before submitting
  push_inputs.sh       input rsync, include-list derived from spec inputs
  pull_results.sh      two-pass result pull (payload + mutable-state refresh)
  bundle.sh            bundle + COMPLETION.txt + sha256 manifest

The point is not convenience. These four things -- what gets submitted, what
counts as done, what gets pulled, what goes in the bundle -- were previously
written by hand as four independent expressions of the same run set, with
nothing forcing them to agree.

Usage:
  wavegen.py <wave_dir_or_spec> [--lanes 0,1,2,3] [--out DIR]
"""
from __future__ import annotations

import argparse
import json
import os
import shlex
import re
import stat
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import wavespec  # noqa: E402
from wavespec import SpecError  # noqa: E402

HEADER = "# GENERATED by fleet/wavegen.py from {spec} -- do not edit by hand.\n"

# Generated scripts must locate the fleet checkout without counting "../"
# levels: the depth changes with --out, and an off-by-one silently sources
# nothing.
ROOT_PREAMBLE = """FLEET_HOME="${{FLEET_HOME:-{root}}}"
[ -f "$FLEET_HOME/fleet/common.sh" ] || {{
  echo "ERROR: fleet checkout not found at FLEET_HOME=$FLEET_HOME" >&2
  echo "       (set FLEET_HOME if it lives elsewhere on this machine)" >&2
  exit 2; }}
"""
COMMON = 'source "$FLEET_HOME/fleet/common.sh"\n'


def _fleet_home() -> Path:
  return Path(__file__).resolve().parent.parent


def _project_repo() -> Path | None:
  """The research repo whose HEAD stamps a wave (FLEET_PROJECT_REPO)."""
  v = os.environ.get("FLEET_PROJECT_REPO", "").strip()
  return Path(os.path.expanduser(v)) if v else None


def _preamble() -> str:
  return ROOT_PREAMBLE.format(root=shlex.quote(str(_fleet_home())))


def _w(path: Path, text: str, executable: bool = False) -> None:
  path.write_text(text)
  if executable:
    path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP)


